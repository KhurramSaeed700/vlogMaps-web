const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const source = fs.readFileSync(path.join(__dirname, '../lib/creator-editor-reducers.ts'), 'utf8')
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText
const moduleUnderTest = { exports: {} }
new Function('module', 'exports', code)(moduleUnderTest, moduleUnderTest.exports)
const { editorDocumentReducer: document, editorHistoryReducer: history } = moduleUnderTest.exports
const initial = Object.freeze({ points: [], tripRoute: {}, routeShapes: {}, savedPlaces: [{ id: 'saved' }] })
const changed = document(initial, { type: 'points', value: points => [...points, { id: 'point' }] })
assert.equal(initial.points.length, 0)
assert.equal(changed.points.length, 1)
assert.equal(changed.savedPlaces, initial.savedPlaces)
assert.equal(document(changed, { type: 'points', value: points => points }), changed)
const restored = document(changed, { type: 'restore-map', state: { points: [], tripRoute: { start: 'restored' }, routeShapes: {} } })
assert.equal(restored.savedPlaces, initial.savedPlaces, 'undo must preserve saved places')
assert.equal(restored.tripRoute.start, 'restored')
assert.equal(document(restored, { type: 'replace', state: initial }), initial, 'video load replaces the whole document')
let stacks = { undoStack: [], redoStack: [] }
assert.equal(history(stacks, { type: 'undo', snapshot: 0 }), stacks)
assert.equal(history(stacks, { type: 'redo', snapshot: 0 }), stacks)
for (let i = 0; i < 60; i++) stacks = history(stacks, { type: 'record', snapshot: i })
assert.equal(stacks.undoStack.length, 50)
assert.equal(stacks.undoStack[0], 10)
stacks = history(stacks, { type: 'undo', snapshot: 60 })
assert.equal(stacks.undoStack.at(-1), 58)
assert.deepEqual(stacks.redoStack, [60])
stacks = history(stacks, { type: 'redo', snapshot: 59 })
assert.equal(stacks.undoStack.at(-1), 59)
assert.deepEqual(stacks.redoStack, [])
stacks = history(stacks, { type: 'undo', snapshot: 60 })
stacks = history(stacks, { type: 'record', snapshot: 61 })
assert.deepEqual(stacks.redoStack, [], 'editing after undo clears the abandoned branch')
assert.deepEqual(history(stacks, { type: 'clear' }), { undoStack: [], redoStack: [] })
console.log('Editor state passed: functional updates, immutable document replacement, saved-place preservation, undo/redo, branching, history limit and reset.')
